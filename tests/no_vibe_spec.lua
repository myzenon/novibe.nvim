describe("no_vibe.load — load order across sources", function()
  it("loads NO_VIBE.md before convention-*.md before learned-*.md", function()
    with_tmp_dir(function(dir)
      write_file(dir .. "/NO_VIBE.md",                     "## *.ts\nfrom novibe\n")
      write_file(dir .. "/.no_vibe/convention-project.md", "## *.ts\nfrom convention\n")
      write_file(dir .. "/.no_vibe/learned-style.md",      "## *.ts\nfrom learned\n")
    end, function()
      local result = no_vibe.load("foo.ts")
      assert.truthy(result)
      local novibe_pos     = result:find("from novibe")
      local convention_pos = result:find("from convention")
      local learned_pos    = result:find("from learned")
      assert.truthy(novibe_pos)
      assert.truthy(convention_pos)
      assert.truthy(learned_pos)
      assert.truthy(novibe_pos < convention_pos)
      assert.truthy(convention_pos < learned_pos)
    end)
  end)

  it("works with only convention files (no NO_VIBE.md)", function()
    with_tmp_dir(function(dir)
      write_file(dir .. "/.no_vibe/convention-project.md", "## always\nrule\n")
    end, function()
      local result = no_vibe.load("foo.ts")
      assert.truthy(result:find("rule"))
    end)
  end)

  it("works with only learned files (no NO_VIBE.md, no conventions)", function()
    with_tmp_dir(function(dir)
      write_file(dir .. "/.no_vibe/learned-style.md", "## always\nrule\n")
    end, function()
      local result = no_vibe.load("foo.ts")
      assert.truthy(result:find("rule"))
    end)
  end)

  it("walks up parent dirs to find .no_vibe/ even without NO_VIBE.md", function()
    with_tmp_dir(function(dir)
      write_file(dir .. "/.no_vibe/convention-project.md", "## always\nfound\n")
    end, function(dir)
      local subdir = dir .. "/a/b"
      vim.fn.mkdir(subdir, "p")
      vim.cmd("cd " .. vim.fn.fnameescape(subdir))
      local result = no_vibe.load("foo.ts")
      assert.truthy(result:find("found"))
    end)
  end)
end)
